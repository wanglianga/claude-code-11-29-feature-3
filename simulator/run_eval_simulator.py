"""Drive a running service through one evaluation scenario.

Loads ``samples/eval/<scenario>/truth.json`` (regenerated by
``scripts/generate_eval_samples.py``), freezes the snapshot, computes the
scenario's reports, and publishes/adopts them as scripted.  Scenarios with a
``revision`` block then freeze the revised snapshot (supplementary
annotation) and compute the next report version in the same series.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import requests

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from simulator.eval_scenarios import build_eval_scenario, scenario_names  # noqa: E402

API_KEY = "dev-api-key"


class Api:
    def __init__(self, base: str, api_key: str = API_KEY):
        self.base = base.rstrip("/")
        self.session = requests.Session()
        self.session.headers.update({"X-API-Key": api_key, "Content-Type": "application/json"})

    def _req(self, method: str, path: str, **kwargs):
        resp = self.session.request(method, f"{self.base}{path}", timeout=60, **kwargs)
        if resp.status_code >= 400:
            raise RuntimeError(f"{method} {path} -> {resp.status_code}: {resp.text[:800]}")
        return resp.json() if resp.content else None

    def post_snapshot(self, payload: dict) -> dict:
        return self._req("POST", "/eval/snapshots", data=json.dumps(payload))

    def post_report(self, key: str, method: str, params: dict | None = None) -> dict:
        body = {"method": method}
        if params:
            body["params"] = params
        return self._req("POST", f"/eval/snapshots/{key}/reports", data=json.dumps(body))

    def publish(self, report_id: int) -> dict:
        return self._req("POST", f"/eval/reports/{report_id}/publish")

    def adopt(self, report_id: int) -> dict:
        return self._req("POST", f"/eval/reports/{report_id}/adopt")


def run_reports(api: Api, snapshot_key: str, specs: list[dict]) -> list[dict]:
    out = []
    for spec in specs:
        report = api.post_report(snapshot_key, spec["method"], spec.get("params"))
        if spec.get("publish"):
            report = api.publish(report["id"])
        if spec.get("adopt"):
            report = api.adopt(report["id"])
        out.append(report)
        print(
            f"  report id={report['id']} series={report['series_id']} "
            f"v{report['report_version']} method={report['method']} "
            f"status={report['status']} adopted={report['adopted']}"
        )
    return out


def run_scenario(name: str, base_url: str, api_key: str = API_KEY) -> dict:
    data = build_eval_scenario(name)
    api = Api(base_url, api_key)
    print(f"scenario {name}: {data['title']}")

    snapshot = api.post_snapshot(data["snapshot"])
    print(
        f"  snapshot {snapshot['snapshot_key']} id={snapshot['id']} "
        f"series={snapshot['series_id']} replay={snapshot['idempotent_replay']}"
    )
    reports = run_reports(api, snapshot["snapshot_key"], data["reports"])

    revision_reports = []
    revision = data.get("revision")
    if revision:
        rev_snapshot = api.post_snapshot(revision["snapshot"])
        print(
            f"  revision snapshot {rev_snapshot['snapshot_key']} id={rev_snapshot['id']} "
            f"series={rev_snapshot['series_id']} revision_of={rev_snapshot['revision_of']}"
        )
        revision_reports = run_reports(api, rev_snapshot["snapshot_key"], revision["reports"])
    return {"snapshot": snapshot, "reports": reports, "revision_reports": revision_reports}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scenario", choices=scenario_names() + ["all"], default="all")
    parser.add_argument("--base-url", default="http://127.0.0.1:8000")
    parser.add_argument("--api-key", default=API_KEY)
    args = parser.parse_args()

    names = scenario_names() if args.scenario == "all" else [args.scenario]
    for name in names:
        run_scenario(name, args.base_url, args.api_key)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
